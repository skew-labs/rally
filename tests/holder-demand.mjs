// Public holder snapshots: prefetch is bounded; closed details stop polling.
import assert from 'node:assert/strict';
globalThis.document={hidden:false};
globalThis.localStorage={getItem:()=>null,setItem:()=>{}};
const realTimeout=globalThis.setTimeout;
globalThis.setTimeout=(fn,ms)=>realTimeout(fn,Math.min(ms,2));
const {warmHolders,mountHolders,cachedHolders}=await import('../holder-ui.js');
const address=n=>'0x'+n.toString(16).padStart(40,'0');
const waiting=id=>({asset:id,indexed:true,holders:[],refreshing:true,waiting:true});
const ready=id=>({...waiting(id),refreshing:false,waiting:false,fetchedAt:Date.now()/1000,total:1,holders:[{address:address(99),amount:'123000'}]});
let reads=0;
const api=async()=>{reads++;return waiting(address(1));};
await Promise.all(Array.from({length:12},()=>warmHolders({api},address(1))));
await new Promise(r=>realTimeout(r,30));
assert.equal(reads,1,'hover intent must not keep polling');
await warmHolders({api},address(1));assert.equal(reads,1,'repeated child pointerovers are throttled');
const host=()=>({isConnected:true,dataset:{},innerHTML:''});
const context=api=>({api,esc:String,age:()=> 'now'});
const first=host();
await mountHolders(context(async()=>{reads++;return ready(address(1));}),first,address(1));
assert.equal(reads,2,'explicit detail bypasses hover cooldown');assert.equal(first.dataset.holdersReady,'true');
assert.match(first.innerHTML,/123K/);assert.equal(cachedHolders(address(1)).asset,address(1));
await warmHolders({api},address(1));assert.equal(reads,2,'fresh data can be reused');
let closeReads=0;const closed=host();
await mountHolders(context(async()=>{closeReads++;closed.isConnected=false;return waiting(address(2));}),closed,address(2));
assert.equal(closeReads,1,'closed panel must not issue further requests');
let recoveryReads=0;const recovering=host();
await mountHolders(context(async()=>++recoveryReads<3?waiting(address(3)):ready(address(3))),recovering,address(3));
assert.equal(recoveryReads,3);assert.equal(recovering.dataset.holdersReady,'true');
let boundedReads=0;
await mountHolders(context(async()=>{boundedReads++;return waiting(address(4));}),host(),address(4));
assert.equal(boundedReads,20,'foreground refresh has one bounded retry loop');
document.hidden=true;
await warmHolders({api:async()=>{throw Error('hidden page fetched');}},address(5));
document.hidden=false;
await assert.rejects(warmHolders({api:async()=>ready(address(7))},address(6)),/identity/);
assert.equal(cachedHolders(address(6)),null);
globalThis.setTimeout=realTimeout;
console.log(JSON.stringify({prefetchReads:1,closedPanelReads:1,foregroundRecoveryReads:3,maxForegroundReads:20,hiddenPageReads:0,identityValidation:true}));
